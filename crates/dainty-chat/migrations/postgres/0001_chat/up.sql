-- Chat's own database (DD15): on Postgres, the database setup gives chat
CREATE TABLE chat_accounts (
    jid_local TEXT PRIMARY KEY,
    account TEXT NOT NULL,
    module TEXT NOT NULL,
    domain TEXT NOT NULL,
    seen_at BIGINT NOT NULL
);
CREATE TABLE chat_room_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room TEXT NOT NULL,
    sender TEXT NOT NULL,
    nick TEXT NOT NULL,
    body TEXT NOT NULL,
    stanza_id TEXT,
    at BIGINT NOT NULL
);
CREATE INDEX chat_room_messages_room ON chat_room_messages (room, id);
CREATE TABLE chat_direct_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender TEXT NOT NULL,
    sender_local TEXT NOT NULL,
    recipient TEXT NOT NULL,
    body TEXT NOT NULL,
    stanza_id TEXT,
    at BIGINT NOT NULL,
    delivered_at BIGINT
);
CREATE INDEX chat_direct_messages_recipient ON chat_direct_messages (recipient, delivered_at, id);
CREATE TABLE chat_mutes (
    account TEXT PRIMARY KEY,
    until_at BIGINT,
    reason TEXT,
    muted_by TEXT NOT NULL,
    at BIGINT NOT NULL
);
