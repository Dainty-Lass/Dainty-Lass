//! Takes every layout fact in `src/facts.rs` from the host's Dumper-7 SDK (`DAINTY_SDK_DIR`, spec §9) and writes
//! them to `$OUT_DIR/sdk_layout.rs`. Without the variable it reads `fixtures/synthetic-sdk`, made-up headers that
//! only the tests use: a DLL built so refuses to export (`SDK_SYNTHETIC`).

#[allow(dead_code, reason = "shared with the library, which uses the rest")]
#[path = "src/sdk_parse.rs"]
mod sdk_parse;

#[allow(dead_code, reason = "shared with the library, which uses the indexes")]
#[path = "src/facts.rs"]
mod facts;

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use sdk_parse::Sdk;

const SDK_VARIABLE: &str = "DAINTY_SDK_DIR";
/// Headers deeper than this are not Dumper-7's layout.
const MAX_DEPTH: usize = 6;

fn main() {
    println!("cargo::rerun-if-env-changed={SDK_VARIABLE}");
    println!("cargo::rerun-if-env-changed=RUSTIC_ISLES_EXPORT_ROOT");
    println!("cargo::rerun-if-changed=src/facts.rs");
    println!("cargo::rerun-if-changed=src/sdk_parse.rs");
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").unwrap_or_default());
    let (dir, synthetic) = match std::env::var_os(SDK_VARIABLE).filter(|value| !value.is_empty()) {
        Some(dir) => (PathBuf::from(dir), false),
        None => (manifest.join("fixtures").join("synthetic-sdk"), true),
    };
    println!("cargo::rerun-if-changed={}", dir.display());
    if synthetic {
        println!("cargo::warning={SDK_VARIABLE} is not set: built on the synthetic SDK, so the DLL exports nothing");
    }

    let mut headers = Vec::new();
    collect_headers(&dir, 0, &mut headers);
    headers.sort();
    if headers.is_empty() {
        fail(&[format!("no .hpp files under {} ({SDK_VARIABLE})", dir.display())]);
    }
    let mut sdk = Sdk::default();
    for header in &headers {
        match std::fs::read(header) {
            Ok(bytes) => sdk.parse(&String::from_utf8_lossy(&bytes)),
            Err(error) => fail(&[format!("cannot read {}: {error}", header.display())]),
        }
    }

    match generate(&sdk, synthetic) {
        Ok(code) => {
            let out = PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default()).join("sdk_layout.rs");
            if let Err(error) = std::fs::write(&out, code) {
                fail(&[format!("cannot write {}: {error}", out.display())]);
            }
        }
        Err(errors) => fail(&errors),
    }
}

fn collect_headers(dir: &Path, depth: usize, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let Ok(kind) = entry.file_type() else {
            continue;
        };
        if kind.is_dir() && depth < MAX_DEPTH {
            collect_headers(&path, depth + 1, out);
        } else if kind.is_file() && path.extension().is_some_and(|ext| ext == "hpp") {
            out.push(path);
        }
    }
}

fn fail(errors: &[String]) -> ! {
    let mut message = format!(
        "the SDK lacks {} fact(s) the exporter needs (src/facts.rs):",
        errors.len()
    );
    for error in errors {
        let _ = write!(message, "\n  - {error}");
    }
    panic!("{message}");
}

fn generate(sdk: &Sdk, synthetic: bool) -> Result<String, Vec<String>> {
    let mut errors = Vec::new();
    let mut code = String::from("// Generated by build.rs from the SDK; never committed.\n");
    let _ = writeln!(code, "pub const SDK_SYNTHETIC: bool = {synthetic};");
    for (id, path) in facts::MEMBERS {
        match sdk.resolve(path) {
            Ok(member) => {
                let _ = writeln!(code, "pub const {id}: Member = {member:?};");
            }
            Err(error) => errors.push(error),
        }
    }
    for (id, path, default) in facts::OPTIONAL_MEMBERS {
        let member = sdk.resolve(path).unwrap_or(*default);
        let _ = writeln!(code, "pub const {id}: Member = {member:?};");
    }
    for (id, name) in facts::SIZES {
        match sdk.size(name) {
            Ok(size) => {
                let _ = writeln!(code, "pub const {id}: u32 = {size};");
            }
            Err(error) => errors.push(error),
        }
    }
    for (id, name, default) in facts::OPTIONAL_SIZES {
        let size = sdk.size(name).unwrap_or(*default);
        let _ = writeln!(code, "pub const {id}: u32 = {size};");
    }
    for (id, name, default) in facts::CONSTS {
        let bare = name.rsplit("::").next().unwrap_or(name);
        match sdk
            .constant(name)
            .or_else(|error| sdk.constant(bare).map_err(|_| error))
        {
            Ok(value) => {
                let _ = writeln!(code, "pub const {id}: i64 = {value};");
            }
            Err(error) => match default {
                Some(value) => {
                    let _ = writeln!(code, "pub const {id}: i64 = {value};");
                }
                None => errors.push(error),
            },
        }
    }
    for (id, path) in facts::ENUMS {
        match sdk.enum_value(path) {
            Ok(value) => {
                let _ = writeln!(code, "pub const {id}: i64 = {value};");
            }
            Err(error) => errors.push(error),
        }
    }
    for (id, owner) in facts::BASE_OWNERS {
        let _ = writeln!(code, "pub const {id}: [Member; {}] = [", facts::BASE_LEN);
        for member in facts::BASE_MEMBERS {
            match sdk.resolve(&format!("{owner}.{member}")) {
                Ok(member) => {
                    let _ = writeln!(code, "    {member:?},");
                }
                Err(error) => errors.push(error),
            }
        }
        code.push_str("];\n");
    }
    if errors.is_empty() { Ok(code) } else { Err(errors) }
}
