-- The admin API's own database (DD23 layer 4, DH2): one key per person, and what each key did.
-- Only SHA-256 of a key is kept (RRA_<id>_<64 hex>), never the key.
CREATE TABLE admin_keys (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    role TEXT NOT NULL,
    key_hash TEXT NOT NULL,
    created_at BIGINT NOT NULL,
    created_by TEXT NOT NULL,
    revoked_at BIGINT,
    revoked_by TEXT
);
CREATE TABLE admin_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at BIGINT NOT NULL,
    key_id TEXT NOT NULL,
    operator TEXT NOT NULL,
    action TEXT NOT NULL,
    target TEXT,
    game TEXT,
    detail TEXT
);
CREATE INDEX admin_actions_key ON admin_actions (key_id, id);
